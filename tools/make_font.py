"""Generate DejaVu UI glyphs, or use --home /path/to/Outfit[wght].ttf for Home (Pillow required)."""
from pathlib import Path
from itertools import groupby
import sys
from PIL import Image, ImageDraw, ImageFont

home = len(sys.argv) == 3 and sys.argv[1] == '--home'
font_dir = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu')
fonts = [(Path(sys.argv[2]), 420), (Path(sys.argv[2]), 650)] if home else [
    (font_dir / 'DejaVuSans.ttf', None), (font_dir / 'DejaVuSans-Bold.ttf', None)
]
FONT_SIZE = 88 if home else 76
WIDTH = HEIGHT = 1024
image = Image.new('L', (WIDTH, HEIGHT))
draw = ImageDraw.Draw(image)
glyphs = []
for font_file, weight in fonts:
    font = ImageFont.truetype(str(font_file), FONT_SIZE)
    if weight is not None:
        font.set_variation_by_axes([weight])
    for code in range(32, 127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        glyphs.append((font, char, left, top, right-left, bottom-top,
                       round(font.getlength(char)*16)))
data = [None] * len(glyphs)
x = y = 1
shelf = 0
for i in sorted(range(len(glyphs)), key=lambda k: -glyphs[k][5]):
    font, char, left, top, w, h, advance = glyphs[i]
    if x+w+1 >= WIDTH:
        x, y, shelf = 1, y+shelf+2, 0
    if y+h+1 >= HEIGHT:
        raise RuntimeError('The glyphs no longer fit inside the atlas.')
    draw.text((x-left, y-top), char, fill=255, font=font, anchor='ls')
    data[i] = (x, y, w, h, left, top, advance)
    x += w+2
    shelf = max(shelf, h)
encoded = []
for value, run in groupby(image.tobytes()):
    n = sum(1 for _ in run)
    while n > 0:
        size = min(n, 255)
        encoded.extend((size, value))
        n -= size
out = Path(__file__).resolve().parents[1] / 'src' / ('home_font_atlas.inc' if home else 'font_atlas.inc')
with out.open('w', encoding='ascii') as f:
    f.write('// Generated by tools/make_font.py. Font license: LICENSE-fonts.txt.\n')
    f.write(f'constexpr int atlasW={WIDTH}, atlasH={HEIGHT}, fontMaster={FONT_SIZE};\n')
    if not home:
        f.write('struct Glyph { int u,v,w,h,left,top,advance; };\n')
    f.write('constexpr Glyph glyphData[] = {\n')
    for glyph in data:
        f.write('    {' + ','.join(map(str, glyph)) + '},\n')
    f.write('};\nconstexpr unsigned char atlasRle[] = {\n')
    for start in range(0, len(encoded), 32):
        f.write('    ' + ','.join(map(str, encoded[start:start+32])) + ',\n')
    f.write('};\n')
